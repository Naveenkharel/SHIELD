"""
agents/mixing_network.py

QMIX Mixing Network + Hypernetworks.

This module combines all agents' individual Q-values into a single joint
value Q_tot, using weights that are DYNAMICALLY GENERATED from the global
state by small "hypernetworks" (rather than being learned directly).

This is TRAINING-ONLY. At deployment, this entire module is discarded and
each router acts greedily on its own local QNetwork (see agents/q_network.py).

Key constraint (monotonicity, IGM condition):
    d Q_tot / d Q_i >= 0   for every agent i

Enforced by applying torch.abs() to all weights produced by the
hypernetworks before they are used in the mixing layers.

Reference: Rashid et al., "QMIX: Monotonic Value Function Factorisation
for Deep Multi-Agent Reinforcement Learning", ICML 2018.
"""

import torch
import torch.nn as nn


class MixingNetwork(nn.Module):
    """
    Combines n_agents individual Q-values into a single Q_tot,
    using weights generated by hypernetworks conditioned on global state.
    """

    def __init__(self, n_agents: int = 14, state_dim: int = 168, mixing_hidden_dim: int = 32,
                 hyper_hidden_dim: int = 64):
        """
        Args:
            n_agents: number of router agents (14 for NSFNET).
            state_dim: size of the global state vector. Default 168 =
                       14 agents x 12 obs features each, concatenated.
            mixing_hidden_dim: size of the mixing network's hidden layer
                                (i.e. width of the first mixing layer).
            hyper_hidden_dim: size of the hidden layer inside each
                               hypernetwork.
        """
        super().__init__()

        self.n_agents = n_agents
        self.state_dim = state_dim
        self.mixing_hidden_dim = mixing_hidden_dim

        # --- Hypernetwork for Layer 1 weights (W1) ---
        # Produces a flat vector of size (n_agents * mixing_hidden_dim),
        # later reshaped into a (n_agents, mixing_hidden_dim) weight matrix.
        self.hyper_w1 = nn.Sequential(
            nn.Linear(state_dim, hyper_hidden_dim),
            nn.ReLU(),
            nn.Linear(hyper_hidden_dim, n_agents * mixing_hidden_dim),
        )

        # --- Hypernetwork for Layer 1 bias (b1) ---
        # Biases are generated with a single linear layer (standard QMIX practice —
        # bias hypernetworks are kept simpler than weight hypernetworks).
        self.hyper_b1 = nn.Linear(state_dim, mixing_hidden_dim)

        # --- Hypernetwork for Layer 2 weights (W2) ---
        # Produces a flat vector of size (mixing_hidden_dim), reshaped into
        # a (mixing_hidden_dim, 1) weight matrix that collapses to one Q_tot.
        self.hyper_w2 = nn.Sequential(
            nn.Linear(state_dim, hyper_hidden_dim),
            nn.ReLU(),
            nn.Linear(hyper_hidden_dim, mixing_hidden_dim),
        )

        # --- Hypernetwork for Layer 2 bias (b2) ---
        # This one is deeper (2 layers), matching the original paper, since
        # the final bias benefits from slightly more capacity.
        self.hyper_b2 = nn.Sequential(
            nn.Linear(state_dim, mixing_hidden_dim),
            nn.ReLU(),
            nn.Linear(mixing_hidden_dim, 1),
        )

    def forward(self, agent_qs: torch.Tensor, states: torch.Tensor) -> torch.Tensor:
        """
        Args:
            agent_qs: tensor of shape (batch_size, n_agents) — each
                      agent's Q-value for the action it took.
            states:   tensor of shape (batch_size, state_dim) — the global
                      state (all agents' observations concatenated).

        Returns:
            q_tot: tensor of shape (batch_size, 1) — the joint team Q-value.
        """
        batch_size = agent_qs.size(0)

        # Reshape agent Q-values into (batch_size, 1, n_agents) so they can
        # be matrix-multiplied against the generated W1 per batch item.
        agent_qs = agent_qs.view(batch_size, 1, self.n_agents)

        # --- Layer 1 ---
        # Generate W1, force non-negative via abs() to enforce monotonicity.
        w1 = torch.abs(self.hyper_w1(states))
        w1 = w1.view(batch_size, self.n_agents, self.mixing_hidden_dim)

        b1 = self.hyper_b1(states)
        b1 = b1.view(batch_size, 1, self.mixing_hidden_dim)

        # (batch, 1, n_agents) x (batch, n_agents, hidden) -> (batch, 1, hidden)
        hidden = torch.bmm(agent_qs, w1) + b1
        hidden = torch.nn.functional.elu(hidden)  # ELU, matching original QMIX paper

        # --- Layer 2 ---
        w2 = torch.abs(self.hyper_w2(states))
        w2 = w2.view(batch_size, self.mixing_hidden_dim, 1)

        b2 = self.hyper_b2(states)
        b2 = b2.view(batch_size, 1, 1)

        # (batch, 1, hidden) x (batch, hidden, 1) -> (batch, 1, 1)
        q_tot = torch.bmm(hidden, w2) + b2

        # Flatten to (batch_size, 1)
        q_tot = q_tot.view(batch_size, 1)
        return q_tot


# -----------------------------------------------------------------------
# Quick manual sanity check (run this file directly to test it works).
# -----------------------------------------------------------------------
if __name__ == "__main__":
    n_agents = 14
    obs_dim = 12
    state_dim = n_agents * obs_dim  # 168

    mixer = MixingNetwork(n_agents=n_agents, state_dim=state_dim)

    batch_size = 8
    dummy_agent_qs = torch.rand(batch_size, n_agents)   # e.g. from QNetwork outputs
    dummy_states = torch.rand(batch_size, state_dim)    # all agents' obs concatenated

    q_tot = mixer(dummy_agent_qs, dummy_states)
    print("Q_tot shape:", q_tot.shape)   # expect (8, 1)
    print("Q_tot values:", q_tot.squeeze())

    # Sanity check monotonicity intuition: increasing one agent's Q should
    # not decrease Q_tot (spot check, not a formal proof).
    bumped_qs = dummy_agent_qs.clone()
    bumped_qs[:, 0] += 1.0  # bump agent 0's Q-value up
    q_tot_bumped = mixer(bumped_qs, dummy_states)
    print("Q_tot increased for all rows after bump:",
          torch.all(q_tot_bumped >= q_tot).item())